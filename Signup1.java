    private void btnCreateAccountActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCreateAccountActionPerformed

        
String firstName = txtFirstname.getText().trim();
String lastName = txtLastname.getText().trim();
String studentId = txtStudentID.getText().trim();
String password = new String(txtPassword.getPassword());
String favoriteFruit = txtFavoriteFruit.getText().trim();
String favoriteSong = txtFavoriteSong.getText().trim();
String confirmPassword = new String(txtConfirmPassword.getPassword());

if (firstName.isEmpty() || lastName.isEmpty()
        || studentId.isEmpty() || password.isEmpty()
        || confirmPassword.isEmpty()
        || favoriteFruit.isEmpty() || favoriteSong.isEmpty()) {

    showError("Please complete all fields, including both security answers.");
    return;
}

if (!password.matches("^(?=.*[a-z])(?=.*[A-Z])(?=.*\\d).+$")) {
    showError("Password must contain an uppercase letter, a lowercase letter, and a number.");
    return;
}

if (!password.equals(confirmPassword)) {
    showError("Passwords do not match.");
    return;
}

if (!studentId.matches("\\d{2}-\\d{4}-\\d{6}")) {
    JOptionPane.showMessageDialog(this,
            "Student ID must be in the format 02-2526-015991.");
    return;
}


String sql = "INSERT INTO users "
        + "(first_name, last_name, student_id, password, favorite_fruit, favorite_song) "
        + "VALUES (?, ?, ?, ?, ?, ?)";

try (java.sql.Connection conn = DBConnection.getConnection();
     java.sql.PreparedStatement pst = conn.prepareStatement(sql)) {

    pst.setString(1, firstName);
    pst.setString(2, lastName);
    pst.setString(3, studentId);
    pst.setString(4, password);
    pst.setString(5, favoriteFruit);
    pst.setString(6, favoriteSong);

    int rows = pst.executeUpdate();

    if (rows > 0) {
        showSuccess("Account created successfully!");

        Login login = new Login();
        login.setVisible(true);
        this.dispose();
    }

} catch (java.sql.SQLException e) {
    showError("Unable to create account: " + e.getMessage());
}
    }//GEN-LAST:event_btnCreateAccountActionPerformed

