private void installStudentIDFormat(javax.swing.JTextField field) {
    ((AbstractDocument) field.getDocument())
            .setDocumentFilter(new DocumentFilter() {

        @Override
        public void insertString(
                FilterBypass fb, int offset, String text,
                AttributeSet attr) throws BadLocationException {
            replace(fb, offset, 0, text, attr);
        }

        @Override
        public void replace(
                FilterBypass fb, int offset, int length,
                String text, AttributeSet attr)
                throws BadLocationException {

            String oldText = fb.getDocument()
                    .getText(0, fb.getDocument().getLength());

            String input = text == null ? "" : text;
            String digits = (oldText.substring(0, offset)
                    + input
                    + oldText.substring(offset + length))
                    .replaceAll("\\D", "");

            if (digits.length() > 12) {
                digits = digits.substring(0, 12);
            }

            StringBuilder formatted = new StringBuilder();

            for (int i = 0; i < digits.length(); i++) {
                if (i == 2 || i == 6) {
                    formatted.append("-");
                }
                formatted.append(digits.charAt(i));
            }

            fb.replace(0, fb.getDocument().getLength(),
                    formatted.toString(), attr);
        }
    });
}
    
    
private void installNameFilter(javax.swing.JTextField field) {
    ((AbstractDocument) field.getDocument())
            .setDocumentFilter(new DocumentFilter() {

        @Override
        public void insertString(
                FilterBypass fb, int offset, String text,
                AttributeSet attr) throws BadLocationException {
            replace(fb, offset, 0, text, attr);
        }

        @Override
        public void replace(
                FilterBypass fb, int offset, int length,
                String text, AttributeSet attr)
                throws BadLocationException {

            String oldText = fb.getDocument()
                    .getText(0, fb.getDocument().getLength());

            String newText = oldText.substring(0, offset)
                    + (text == null ? "" : text)
                    + oldText.substring(offset + length);

            // Allow letters, spaces, hyphens, and apostrophes only.
            if (!newText.matches("[\\p{L} '\\u002D]*")) {
                return;
            }

            // Capitalize the first letter of each word.
            StringBuilder result = new StringBuilder();
            boolean capitalizeNext = true;

            for (char c : newText.toCharArray()) {
                if (Character.isLetter(c)) {
                    result.append(capitalizeNext
                            ? Character.toUpperCase(c)
                            : Character.toLowerCase(c));
                    capitalizeNext = false;
                } else {
                    result.append(c);
                    capitalizeNext = true;
                }
            }

            fb.replace(0, fb.getDocument().getLength(),
                    result.toString(), attr);
        }
    });
}
    

