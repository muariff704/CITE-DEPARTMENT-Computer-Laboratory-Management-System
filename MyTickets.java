    private void loadTickets(int userId) {
    DefaultTableModel model =
            (DefaultTableModel) tblTickets.getModel();

    model.setRowCount(0);

    String sql = "SELECT ticket_number, building, laboratory, "
        + "computer_number, problem_category, status, reported_at "
        + "FROM problem_reports "
        + "WHERE user_id = ? "
        + "ORDER BY reported_at DESC";

    try (Connection conn = DBConnection.getConnection();
         PreparedStatement pst = conn.prepareStatement(sql)) {

        pst.setInt(1, userId);

        try (ResultSet rs = pst.executeQuery()) {
            while (rs.next()) {
                model.addRow(new Object[]{
                    rs.getString("ticket_number"),
                    rs.getString("building"),
                    rs.getString("laboratory"),
                    rs.getString("computer_number"),
                    rs.getString("problem_category"),
                    rs.getString("status"),
                    rs.getTimestamp("reported_at")
                });
            }
        }

    } catch (Exception e) {
        JOptionPane.showMessageDialog(
                this,
                "Unable to load tickets: " + e.getMessage(),
                "Database Error",
                JOptionPane.ERROR_MESSAGE
        );
        e.printStackTrace();
    }
}
    
