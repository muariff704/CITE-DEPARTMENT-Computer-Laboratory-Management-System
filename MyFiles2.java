    private void tblFilesMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblFilesMouseClicked
        int row = tblFiles.getSelectedRow();

if (row >= 0) {

    String action = tblFiles.getValueAt(row, 4).toString();

    if (action.equals("Download / Delete")){
        
        

        String fileName = tblFiles.getValueAt(row, 0).toString();
        String filePath = tblFiles.getValueAt(row, 5).toString();

        File sourceFile = new File(filePath);

        if (!sourceFile.exists()) {

            JOptionPane.showMessageDialog(
                    this,
                    "File not found."
            );

            return;
        }

        JFileChooser fileChooser = new JFileChooser();
        fileChooser.setSelectedFile(new File(fileName));

        int result = fileChooser.showSaveDialog(this);

        if (result == JFileChooser.APPROVE_OPTION) {

            File destinationFile = fileChooser.getSelectedFile();

            try {

                Files.copy(
                        sourceFile.toPath(),
                        destinationFile.toPath(),
                        StandardCopyOption.REPLACE_EXISTING
                );

                JOptionPane.showMessageDialog(
                        this,
                        "File downloaded successfully!"
                );

            } catch (Exception e) {

                JOptionPane.showMessageDialog(
                        this,
                        "Download failed: " + e.getMessage()
                );
            }
        }
    }
}
    }//GEN-LAST:event_tblFilesMouseClicked

