    private void btnUploadActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUploadActionPerformed
        if (selectedFile == null) {

    JOptionPane.showMessageDialog(this, "Please choose a file first.");
    return;

}

try {

    File storageFolder = new File("CITE_FILE_STORAGE");

    if (!storageFolder.exists()) {
        storageFolder.mkdirs();
    }

    File destinationFile =
            new File(storageFolder, selectedFile.getName());

    Files.copy(
            selectedFile.toPath(),
            destinationFile.toPath(),
            StandardCopyOption.REPLACE_EXISTING
    );

    String sql = "INSERT INTO files "
            + "(user_id, file_name, file_type, file_size, file_path) "
            + "VALUES (?, ?, ?, ?, ?)";

            try (Connection conn = DBConnection.getConnection()) {
                if (conn == null) {
                    JOptionPane.showMessageDialog(this, "Database connection failed.");
                    return;
                }
                
        try (PreparedStatement pst = conn.prepareStatement(sql)) {
            pst.setInt(1, Session.userId);
            pst.setString(2, selectedFile.getName());
            pst.setString(3, Files.probeContentType(selectedFile.toPath()));
            pst.setLong(4, selectedFile.length());
            pst.setString(5, destinationFile.getAbsolutePath());
            
            pst.executeUpdate();
        }
            }

    JOptionPane.showMessageDialog(
            this,
            "File uploaded successfully!"
    );

} catch (HeadlessException | IOException | SQLException e) {

    JOptionPane.showMessageDialog(
            this,
            "Upload failed: " + e.getMessage()
    );

}
    }//GEN-LAST:event_btnUploadActionPerformed

