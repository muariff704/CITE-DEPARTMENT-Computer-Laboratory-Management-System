private void loadAccountInfo() {
    String sql = "SELECT first_name, last_name, student_id "
               + "FROM users WHERE id = ?";

    try (java.sql.Connection conn = DBConnection.getConnection()) {

        if (conn == null) {
            javax.swing.JOptionPane.showMessageDialog(
                this,
                "Cannot connect to the database.",
                "Database Error",
                javax.swing.JOptionPane.ERROR_MESSAGE
            );
            return;
        }

        try (java.sql.PreparedStatement pst = conn.prepareStatement(sql)) {
            pst.setInt(1, Session.userId);

            try (java.sql.ResultSet rs = pst.executeQuery()) {
                if (rs.next()) {
                    String firstName = rs.getString("first_name");
                    String lastName = rs.getString("last_name");
                    String studentId = rs.getString("student_id");

                    lblFirstname.setText(firstName + " " + lastName);
                    lblStudentId.setText(studentId);
                } else {
                    javax.swing.JOptionPane.showMessageDialog(
                        this,
                        "Account details not found.",
                        "Account Error",
                        javax.swing.JOptionPane.ERROR_MESSAGE
                    );
                }
            }
        }

    } catch (java.sql.SQLException e) {
        javax.swing.JOptionPane.showMessageDialog(
            this,
            "Error loading account details: " + e.getMessage(),
            "Database Error",
            javax.swing.JOptionPane.ERROR_MESSAGE
        );
    }
}

