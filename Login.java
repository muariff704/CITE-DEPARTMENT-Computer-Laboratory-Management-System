private void installStudentIDFormat(javax.swing.JTextField field) {

    ((AbstractDocument) field.getDocument())
            .setDocumentFilter(new DocumentFilter() {

        @Override
        public void insertString(
                FilterBypass fb, int offset, String text,
                AttributeSet attr) throws BadLocationException {

            replace(fb, offset, 0, text, attr);
        }

        @Override
        public void replace(
                FilterBypass fb, int offset, int length,
                String text, AttributeSet attr)
                throws BadLocationException {

            String oldText = fb.getDocument()
                    .getText(0, fb.getDocument().getLength());

            String input = text == null ? "" : text;

            String newText = oldText.substring(0, offset)
                    + input
                    + oldText.substring(offset + length);

            // If letters are present, allow an alphanumeric ID
            if (newText.matches(".*[A-Za-z].*")) {

                String alphanumeric =
                        newText.replaceAll("[^A-Za-z0-9]", "");

                // Limit the ID to 20 characters
                if (alphanumeric.length() > 20) {
                    alphanumeric = alphanumeric.substring(0, 20);
                }

                fb.replace(
                        0,
                        fb.getDocument().getLength(),
                        alphanumeric,
                        attr
                );

                return;
            }

            // Keep the existing formatting for numeric Student IDs
            String digits = newText.replaceAll("\\D", "");

            if (digits.length() > 12) {
                digits = digits.substring(0, 12);
            }

            StringBuilder formatted = new StringBuilder();

            for (int i = 0; i < digits.length(); i++) {

                if (i == 2 || i == 6) {
                    formatted.append("-");
                }

                formatted.append(digits.charAt(i));
            }

            fb.replace(
                    0,
                    fb.getDocument().getLength(),
                    formatted.toString(),
                    attr
            );
        }
    });
}


