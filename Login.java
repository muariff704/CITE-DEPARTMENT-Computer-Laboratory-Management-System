    private void btnLoginActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnLoginActionPerformed
        


    String studentId = txtStudentId.getText().trim();
    String password = new String(txtPassword.getPassword());

    // Check required fields
    if (studentId.isEmpty() || password.isEmpty()) {
        JOptionPane.showMessageDialog(
                this,
                "Please enter your ID and password.",
                "Login Error",
                JOptionPane.ERROR_MESSAGE
        );
        return;
    }

    String sql = "SELECT id, first_name, student_id, role "
            + "FROM users WHERE student_id = ? AND password = ?";

    try (Connection conn = DBConnection.getConnection()) {

        if (conn == null) {
            JOptionPane.showMessageDialog(
                    this,
                    "Cannot connect to the database.",
                    "Database Error",
                    JOptionPane.ERROR_MESSAGE
            );
            return;
        }

        try (PreparedStatement pst = conn.prepareStatement(sql)) {

            pst.setString(1, studentId);
            pst.setString(2, password);

            try (ResultSet rs = pst.executeQuery()) {

                if (rs.next()) {

                    Session.userId = rs.getInt("id");
                    Session.username = rs.getString("student_id");

                    String role = rs.getString("role");

                    if ("admin".equalsIgnoreCase(role)) {

                        // Open the Admin Dashboard
                        new AdminDashboard().setVisible(true);

                    } else {

                        // Open the Student Dashboard
                        JOptionPane.showMessageDialog(
                                this,
                                "Welcome, " + rs.getString("first_name") + "!",
                                "Login Successful",
                                JOptionPane.INFORMATION_MESSAGE
                        );

                        new Homepage().setVisible(true);
                    }

                    // Close Login after a successful login
                    this.dispose();

                } else {

                    JOptionPane.showMessageDialog(
                            this,
                            "Incorrect ID or password.",
                            "Login Failed",
                            JOptionPane.ERROR_MESSAGE
                    );
                }
            }
        }

    } catch (SQLException ex) {

        JOptionPane.showMessageDialog(
                this,
                "Login failed: " + ex.getMessage(),
                "Database Error",
                JOptionPane.ERROR_MESSAGE
        );
    }


    }//GEN-LAST:event_btnLoginActionPerformed

