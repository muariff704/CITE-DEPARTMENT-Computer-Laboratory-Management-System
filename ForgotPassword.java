    private void btnVerifyActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnVerifyActionPerformed

String studentId = txtStudentID.getText().trim();
String favoriteFruit = txtFavoriteFruit.getText().trim();
String favoriteSong = txtFavoriteSong.getText().trim();

if (studentId.isEmpty() || favoriteFruit.isEmpty()
        || favoriteSong.isEmpty()) {
    JOptionPane.showMessageDialog(this,
            "Please complete all fields.");
    return;
}

String sql = "SELECT * FROM users "
        + "WHERE student_id = ? "
        + "AND LOWER(favorite_fruit) = LOWER(?) "
        + "AND LOWER(favorite_song) = LOWER(?)";

try (java.sql.Connection conn = DBConnection.getConnection();
     java.sql.PreparedStatement pst = conn.prepareStatement(sql)) {

    pst.setString(1, studentId);
    pst.setString(2, favoriteFruit);
    pst.setString(3, favoriteSong);

    try (java.sql.ResultSet rs = pst.executeQuery()) {
        if (rs.next()) {
            JOptionPane.showMessageDialog(this,
                    "Identity verified! You may now reset your password.");
identityVerified = true;
             txtNewPassword.setEnabled(true);
             txtConfirmNewPassword.setEnabled(true);
             btnResetPassword.setEnabled(true);
txtStudentID.setEnabled(false);
txtFavoriteFruit.setEnabled(false);
txtFavoriteSong.setEnabled(false);
    txtNewPassword.requestFocus();

            // We will add the new-password fields next.
        } else {
            JOptionPane.showMessageDialog(this,
                    "Incorrect Student ID or security answers.",
                    "Verification Failed",
                    JOptionPane.ERROR_MESSAGE);
        }
    }

} catch (java.sql.SQLException e) {
    JOptionPane.showMessageDialog(this,
            "Database error: " + e.getMessage(),
            "Error",
            JOptionPane.ERROR_MESSAGE);
}
       
    }//GEN-LAST:event_btnVerifyActionPerformed

