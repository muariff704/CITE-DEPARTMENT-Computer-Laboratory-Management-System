    private void btnResetPasswordActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnResetPasswordActionPerformed
if (!identityVerified) {
    JOptionPane.showMessageDialog(this,
            "Please verify your identity first.");
    return;
}        
String studentId = txtStudentID.getText().trim();
String newPassword = new String(txtNewPassword.getPassword());
String confirmPassword =
        new String(txtConfirmNewPassword.getPassword());

if (newPassword.isEmpty() || confirmPassword.isEmpty()) {
    JOptionPane.showMessageDialog(this,
            "Please complete both password fields.");
    return;
}

if (!newPassword.matches("^(?=.*[a-z])(?=.*[A-Z])(?=.*\\d).+$")) {
    JOptionPane.showMessageDialog(this,
            "Password must contain an uppercase letter, a lowercase letter, and a number.");
    return;
}

if (!newPassword.equals(confirmPassword)) {
    JOptionPane.showMessageDialog(this,
            "Passwords do not match.");
    return;
}

String sql = "UPDATE users SET password = ? WHERE student_id = ?";

try (java.sql.Connection conn = DBConnection.getConnection();
     java.sql.PreparedStatement pst = conn.prepareStatement(sql)) {

    pst.setString(1, newPassword);
    pst.setString(2, studentId);

    int rows = pst.executeUpdate();

    if (rows > 0) {
        JOptionPane.showMessageDialog(this,
                "Password reset successfully! You can now log in.");

        Login login = new Login();
        login.setLocationRelativeTo(null);
        login.setVisible(true);
        this.dispose();
    } else {
        JOptionPane.showMessageDialog(this,
                "Account not found. Please verify your Student ID again.");
    }

} catch (java.sql.SQLException e) {
    JOptionPane.showMessageDialog(this,
            "Database error: " + e.getMessage());
}
    }//GEN-LAST:event_btnResetPasswordActionPerformed

