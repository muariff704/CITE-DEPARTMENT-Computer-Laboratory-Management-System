private void loadTicketById() {

    String ticketNumber = txtSearchTicketId.getText().trim();

    if (ticketNumber.isEmpty()) {
        JOptionPane.showMessageDialog(
                this,
                "Please enter a Ticket ID.",
                "Missing Ticket ID",
                JOptionPane.WARNING_MESSAGE
        );
        return;
    }

    
String sql = "SELECT p.ticket_number, u.student_id, "
        + "p.building, p.laboratory, p.computer_number, "
        + "p.problem_category, p.description, p.status, "
        + "p.admin_notes "
        + "FROM problem_reports p "
        + "LEFT JOIN users u ON p.user_id = u.id "
        + "WHERE p.ticket_number = ? "
        + "AND (? = 'All Statuses' OR p.status = ?) "
        + "AND (? = 'All Buildings' OR p.building = ?)";

    try (Connection conn = DBConnection.getConnection()) {

        if (conn == null) {
            JOptionPane.showMessageDialog(
                    this,
                    "Could not connect to the database.",
                    "Database Error",
                    JOptionPane.ERROR_MESSAGE
            );
            return;
        }

        try (PreparedStatement pst = conn.prepareStatement(sql)) {

           
pst.setString(1, ticketNumber);

String selectedStatus =
        (String) cmbFilterStatus.getSelectedItem();

if (selectedStatus == null) {
    selectedStatus = "All Statuses";
}

pst.setString(2, selectedStatus);
pst.setString(3, selectedStatus);

String selectedBuilding =
        (String) cmbFilterBuilding.getSelectedItem();

if (selectedBuilding == null) {
    selectedBuilding = "All Buildings";
}

pst.setString(4, selectedBuilding);
pst.setString(5, selectedBuilding);


            try (ResultSet rs = pst.executeQuery()) {

                if (rs.next()) {

                    selectedTicketNumber =
                            rs.getString("ticket_number");

                    String studentId = rs.getString("student_id");
                    String building = rs.getString("building");
                    String laboratory = rs.getString("laboratory");
                    String computer = rs.getString("computer_number");
                    String category = rs.getString("problem_category");
                    String description = rs.getString("description");
                    String status = rs.getString("status");
                    String notes = rs.getString("admin_notes");

                    if (studentId == null) {
                        studentId = "Unknown";
                    }

                    lblTicketIdValue.setText(
                            "Ticket ID: " + selectedTicketNumber
                    );

                    lblStudentValue.setText(
                            "Student: " + studentId
                    );

                    lblLocationValue.setText(
                            "Location: " + building + " - "
                            + laboratory + " - PC " + computer
                    );

                    lblProblemValue.setText(
                            "Problem: " + category + " - "
                            + description
                    );

                    lblCurrentStatusValue.setText(
                            "Current Status: " + status
                    );

                    cmbUpdateStatus.setSelectedItem(status);

                    txtAdminNotes.setText(
                            notes == null ? "" : notes
                    );

                } else {

                    selectedTicketNumber = null;

                    JOptionPane.showMessageDialog(
                            this,
                            "No ticket found with ID: " + ticketNumber,
                            "Ticket Not Found",
                            JOptionPane.INFORMATION_MESSAGE
                    );

                    lblTicketIdValue.setText(
                            "Ticket ID: No ticket selected"
                    );
                    lblStudentValue.setText("Student: —");
                    lblLocationValue.setText("Location: —");
                    lblProblemValue.setText("Problem: —");
                    lblCurrentStatusValue.setText(
                            "Current Status: —"
                    );
                    txtAdminNotes.setText("");
                }
            }
        }

    } catch (SQLException ex) {

        JOptionPane.showMessageDialog(
                this,
                "Failed to load ticket:\n" + ex.getMessage(),
                "Database Error",
                JOptionPane.ERROR_MESSAGE
        );
    
}

    }//GEN-LAST:event_txtSearchTicketIdActionPerformed

