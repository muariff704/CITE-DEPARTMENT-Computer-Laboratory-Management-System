    private void btnSaveChangesActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveChangesActionPerformed




    // Make sure a ticket has been searched for
    if (selectedTicketNumber == null) {
        JOptionPane.showMessageDialog(
                this,
                "Please search for a ticket first.",
                "No Ticket Selected",
                JOptionPane.WARNING_MESSAGE
        );
        return;
    }

    String newStatus =
            (String) cmbUpdateStatus.getSelectedItem();

    String adminNotes = txtAdminNotes.getText().trim();

    if (newStatus == null) {
        JOptionPane.showMessageDialog(
                this,
                "Please select a ticket status.",
                "Missing Status",
                JOptionPane.WARNING_MESSAGE
        );
        return;
    }

    String sql = "UPDATE problem_reports "
            + "SET status = ?, admin_notes = ?, "
            + "updated_at = CURRENT_TIMESTAMP "
            + "WHERE ticket_number = ?";

    try (Connection conn = DBConnection.getConnection()) {

        if (conn == null) {
            JOptionPane.showMessageDialog(
                    this,
                    "Could not connect to the database.",
                    "Database Error",
                    JOptionPane.ERROR_MESSAGE
            );
            return;
        }

        try (PreparedStatement pst = conn.prepareStatement(sql)) {

            pst.setString(1, newStatus);
            pst.setString(2, adminNotes);
            pst.setString(3, selectedTicketNumber);

            int rowsUpdated = pst.executeUpdate();

            if (rowsUpdated > 0) {

                lblCurrentStatusValue.setText(
                        "Current Status: " + newStatus
                );

                JOptionPane.showMessageDialog(
                        this,
                        "Ticket status and admin notes saved successfully!",
                        "Changes Saved",
                        JOptionPane.INFORMATION_MESSAGE
                );

            } else {
                JOptionPane.showMessageDialog(
                        this,
                        "The ticket could not be updated.",
                        "Update Failed",
                        JOptionPane.WARNING_MESSAGE
                );
            }
        }

    } catch (SQLException ex) {
        JOptionPane.showMessageDialog(
                this,
                "Failed to save changes:\n" + ex.getMessage(),
                "Database Error",
                JOptionPane.ERROR_MESSAGE
        );
    }
        
    }//GEN-LAST:event_btnSaveChangesActionPerformed

