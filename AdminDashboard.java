    private void loadDashboardData() {
    try (Connection conn = DBConnection.getConnection()) {

        String[] statuses = {
            "Total Tickets", "Pending",
            "In Progress", "Resolved"
        };

        String totalSql =
            "SELECT COUNT(*) FROM problem_reports";

        try (PreparedStatement pst =
                 conn.prepareStatement(totalSql);
             ResultSet rs = pst.executeQuery()) {

            if (rs.next()) {
                lblTotalTickets.setText(
                    String.valueOf(rs.getInt(1))
                );
            }
        }

        String statusSql =
            "SELECT status, COUNT(*) AS total "
          + "FROM problem_reports GROUP BY status";

        try (PreparedStatement pst =
                 conn.prepareStatement(statusSql);
             ResultSet rs = pst.executeQuery()) {

            lblPending.setText("0");
            lblInProgress.setText("0");
            lblResolved.setText("0");

            while (rs.next()) {
                String status = rs.getString("status");
                int total = rs.getInt("total");

                if ("Pending".equalsIgnoreCase(status)) {
                    lblPending.setText(String.valueOf(total));
                } else if ("In Progress".equalsIgnoreCase(status)) {
                    lblInProgress.setText(String.valueOf(total));
                } else if ("Resolved".equalsIgnoreCase(status)) {
                    lblResolved.setText(String.valueOf(total));
                }
            }
        }

        DefaultTableModel model =
    (DefaultTableModel) jTable.getModel();

model.setRowCount(0);

        String recentSql =
            "SELECT p.ticket_number, u.student_id, "
          + "p.building, p.laboratory, p.computer_number, "
          + "p.problem_category, p.status, p.reported_at "
          + "FROM problem_reports p "
          + "LEFT JOIN users u ON p.user_id = u.id "
          + "ORDER BY p.reported_at DESC LIMIT 10";

        try (PreparedStatement pst =
                 conn.prepareStatement(recentSql);
             ResultSet rs = pst.executeQuery()) {

            while (rs.next()) {
                model.addRow(new Object[]{
                    rs.getString("ticket_number"),
                    rs.getString("student_id"),
                    rs.getString("building"),
                    rs.getString("laboratory"),
                    rs.getString("computer_number"),
                    rs.getString("problem_category"),
                    rs.getString("status"),
                    rs.getTimestamp("reported_at")
                });
            }
        }

    } catch (Exception e) {
        JOptionPane.showMessageDialog(this,
            "Unable to load dashboard: " + e.getMessage(),
            "Database Error",
            JOptionPane.ERROR_MESSAGE);
    }
}
