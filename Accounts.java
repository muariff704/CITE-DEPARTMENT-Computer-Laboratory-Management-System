private void loadAccounts() {

    DefaultTableModel model =
            (DefaultTableModel) tblAccounts.getModel();

    model.setRowCount(0);

    String searchText = txtSearchAccount.getText().trim();
    String searchPattern = "%" + searchText + "%";

    String selectedRole =
            (String) cmbFilterRole.getSelectedItem();

    if (selectedRole == null) {
        selectedRole = "All Roles";
    }

    String sql = "SELECT id, "
            + "CONCAT(first_name, ' ', last_name) AS full_name, "
            + "student_id, role "
            + "FROM users "
            + "WHERE (CONCAT(first_name, ' ', last_name) LIKE ? "
            + "OR student_id LIKE ?) "
            + "AND (? = 'All Roles' OR LOWER(role) = LOWER(?)) "
            + "ORDER BY id";

    try (Connection conn = DBConnection.getConnection()) {

        if (conn == null) {
            JOptionPane.showMessageDialog(
                    this,
                    "Could not connect to the database.",
                    "Database Error",
                    JOptionPane.ERROR_MESSAGE
            );
            return;
        }

        try (PreparedStatement pst = conn.prepareStatement(sql)) {

            pst.setString(1, searchPattern);
            pst.setString(2, searchPattern);
            pst.setString(3, selectedRole);
            pst.setString(4, selectedRole);

            try (ResultSet rs = pst.executeQuery()) {

                while (rs.next()) {

                    model.addRow(new Object[]{
                        rs.getInt("id"),
                        rs.getString("full_name"),
                        rs.getString("student_id"),
                        rs.getString("role")
                    });
                }
            }
        }

    } catch (SQLException ex) {

        JOptionPane.showMessageDialog(
                this,
                "Failed to load accounts:\n" + ex.getMessage(),
                "Database Error",
                JOptionPane.ERROR_MESSAGE
        );
    }
}

