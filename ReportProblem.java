    private void btnSubmitActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSubmitActionPerformed
String building = (String) cmbBuilding.getSelectedItem();
String laboratory = (String) cmbLaboratory.getSelectedItem();
String computerNumber = txtComputerNumber.getText().trim();
String category = (String) cmbProblemCategory.getSelectedItem();
String description = txtDescription.getText().trim();

if (building == null || laboratory == null || category == null) {
    JOptionPane.showMessageDialog(this,
            "Please select a building, laboratory, and category.");
    return;
}

if (computerNumber.isEmpty() || description.isEmpty()) {
    JOptionPane.showMessageDialog(this,
            "Please complete all fields.");
    return;
}

String sql = "INSERT INTO problem_reports "
        + "(ticket_number, user_id, building, laboratory, "
        + "computer_number, problem_category, description, status) "
        + "VALUES (?, ?, ?, ?, ?, ?, ?, ?)";

try (java.sql.Connection conn = DBConnection.getConnection();
     java.sql.PreparedStatement pst = conn.prepareStatement(sql)) {

    String ticketNumber = "TKT-" + System.currentTimeMillis();

    pst.setString(1, ticketNumber);

    // Replace this with the actual logged-in user's database ID.
    pst.setInt(2, Session.userId);

    pst.setString(3, building);
    pst.setString(4, laboratory);
    pst.setString(5, computerNumber);
    pst.setString(6, category);
    pst.setString(7, description);
    pst.setString(8, "Pending");

    pst.executeUpdate();

    JOptionPane.showMessageDialog(this,
            "Problem report submitted successfully!\n"
            + "Ticket ID: " + ticketNumber);

    txtComputerNumber.setText("");
    txtDescription.setText("");

} catch (Exception e) {
    JOptionPane.showMessageDialog(this,
            "Failed to save report: " + e.getMessage(),
            "Database Error",
            JOptionPane.ERROR_MESSAGE);
    e.printStackTrace();
}
    }//GEN-LAST:event_btnSubmitActionPerformed

